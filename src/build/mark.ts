import { raw, type Raw } from './html.ts';
import { LOGO_BOTTOM, LOGO_PK, LOGO_TOP } from './logo-art.ts';

/** Grains along a curved stem, computed once (no inline styles: CSP-safe). */
function sprig(): string {
  // Cubic stem on the left side of the oval, between the two arcs of lettering.
  const P = [[33, 74], [24, 66], [20, 52], [25, 37]] as const;
  const at = (t: number) => {
    const u = 1 - t;
    const x = u ** 3 * P[0][0] + 3 * u * u * t * P[1][0] + 3 * u * t * t * P[2][0] + t ** 3 * P[3][0];
    const y = u ** 3 * P[0][1] + 3 * u * u * t * P[1][1] + 3 * u * t * t * P[2][1] + t ** 3 * P[3][1];
    const dx = 3 * u * u * (P[1][0] - P[0][0]) + 6 * u * t * (P[2][0] - P[1][0]) + 3 * t * t * (P[3][0] - P[2][0]);
    const dy = 3 * u * u * (P[1][1] - P[0][1]) + 6 * u * t * (P[2][1] - P[1][1]) + 3 * t * t * (P[3][1] - P[2][1]);
    return { x, y, a: (Math.atan2(dy, dx) * 180) / Math.PI };
  };
  const grains: string[] = [];
  const ts = [0.2, 0.33, 0.46, 0.59, 0.72, 0.85];
  ts.forEach((t, i) => {
    const p = at(t);
    for (const side of [-1, 1]) {
      const nx = p.x + side * 3 * Math.cos(((p.a + 90) * Math.PI) / 180);
      const ny = p.y + side * 3 * Math.sin(((p.a + 90) * Math.PI) / 180);
      const rot = p.a + 90 + side * 28;
      grains.push(`<ellipse class="mk-grain mk-g${i}" cx="${nx.toFixed(2)}" cy="${ny.toFixed(2)}" rx="1.7" ry="3.6" transform="rotate(${rot.toFixed(1)} ${nx.toFixed(2)} ${ny.toFixed(2)})"/>`);
    }
  });
  const tip = at(1);
  grains.push(`<ellipse class="mk-grain mk-g6" cx="${tip.x.toFixed(2)}" cy="${(tip.y - 2.3).toFixed(2)}" rx="1.7" ry="3.7" transform="rotate(${(tip.a + 90).toFixed(1)} ${tip.x.toFixed(2)} ${(tip.y - 2.3).toFixed(2)})"/>`);
  return `<path class="mk-stem" pathLength="100" d="M${P[0].join(' ')} C${P[1].join(' ')} ${P[2].join(' ')} ${P[3].join(' ')}"/>${grains.join('')}`;
}

const SPRIG = sprig();
/** One path per letter cluster, numbered so the loader can form them in order. */
const letters = (paths: readonly string[], cls: string) =>
  paths.map((d, i) => `<path class="${cls} mk-i${i}" pathLength="100" d="${d}"/>`).join('');
const TOP = letters(LOGO_TOP, 'mk-l');
const BOTTOM = letters(LOGO_BOTTOM, 'mk-l');
const PK = letters(LOGO_PK, 'mk-m');

/**
 * @param id unique prefix for gradient ids (the header and the loader both use the mark)
 */
export function pkMark(id: string, cls: string, title?: string): Raw {
  const g = `${id}-gold`;
  const c = `${id}-cream`;
  const b = `${id}-brown`;
  return raw(`<svg class="${cls}" viewBox="0 0 140 96" ${title ? `role="img" aria-label="${title}"` : 'aria-hidden="true" focusable="false"'}>
<defs>
<linearGradient id="${g}" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#e9d39c"/><stop offset=".45" stop-color="#c49a4a"/><stop offset="1" stop-color="#8d6727"/></linearGradient>
<linearGradient id="${b}" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#6b4423"/><stop offset="1" stop-color="#3a2414"/></linearGradient>
<radialGradient id="${c}" cx=".42" cy=".3" r=".85"><stop offset="0" stop-color="#fffdf7"/><stop offset=".7" stop-color="#f7efdf"/><stop offset="1" stop-color="#ecdfc4"/></radialGradient>
</defs>
<ellipse class="mk-oval" pathLength="100" cx="70" cy="48" rx="66" ry="44" fill="url(#${c})" stroke="url(#${g})" stroke-width="2.4"/>
<ellipse class="mk-ring" pathLength="100" cx="70" cy="48" rx="60.5" ry="38.6" fill="none" stroke="url(#${g})" stroke-width=".8"/>
<g class="mk-sprig" fill="url(#${g})" stroke="url(#${g})">${SPRIG}</g>
<g class="mk-sprig mk-sprig--r" fill="url(#${g})" stroke="url(#${g})" transform="translate(140 0) scale(-1 1)">${SPRIG}</g>
<g class="mk-top" fill="#7a5226" stroke="#7a5226">${TOP}</g>
<g class="mk-bottom" fill="#8d6727" stroke="#8d6727">${BOTTOM}</g>
<g class="mk-pk" fill="url(#${b})" stroke="#835d1c">${PK}</g>
</svg>`);
}
