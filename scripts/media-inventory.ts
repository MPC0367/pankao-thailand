/**
 * Media inventory (premium audit, 20 Nov 2026, P1 "Media inventory: classify 61 legacy files + stock; request
 * originals"). Lists every file in the research copy of the 2014 site and every licensed illustrative photograph,
 * with its source class, size, where it is used and what to ask the company for.
 *   node scripts/media-inventory.ts   → docs/generated/MEDIA_INVENTORY.md
 * Needs ../documents/research/legacy-site/images (local only; never in the repository).
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { assets } from '../src/content/assets.ts';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const DIR = resolve(ROOT, '../documents/research/legacy-site/images');
if (!existsSync(DIR)) { console.error(`media-inventory: ${DIR} not found (local research copy)`); process.exit(1); }

const size = (f: string) => {
  try { return execFileSync('ffprobe', ['-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=width,height', '-of', 'csv=p=0:s=x', join(DIR, f)], { encoding: 'utf8' }).trim(); } catch { return '?'; }
};

type Kind = { cls: string; proves: string; action: string };
const kind = (f: string): Kind => {
  if (/^mr_noodles_package|^product_mr_noodles\.jpg|^mr_noodles\.jpg/.test(f)) return { cls: 'A · actual pack', proves: 'Own brand packs (2014 print)', action: 'Request the original file and a current pack photograph' };
  if (/^rice_(vermicelli|stick|flake|brown)\.jpg$/.test(f)) return { cls: 'A · actual product', proves: 'Dry noodle texture of each format', action: 'Request originals; new macro shots (audit: 4 dry macros)' };
  if (/^product_rice_.*_(th|en|vn)\.jpg$/.test(f) && !/dish/.test(f)) return { cls: 'A · product tile with label in the image', proves: 'Same textures, label baked into the raster', action: 'Not used (text in raster)' };
  if (/_bg\.jpg$/.test(f) && /^rice_/.test(f) || /dish/.test(f)) return { cls: 'Archive · prepared dish', proves: 'Serving context only; origin and styling not documented', action: 'Ask whether the company owns these and who photographed them' };
  if (/^process_(factory|rice|lab|noodle)|^history_img01|^contact_img01/.test(f)) return { cls: 'A · facility / process', proves: 'Plant interior, trays, lab, building (2014)', action: 'Request originals; new process, QA, packing and exterior shots' };
  if (/^(history_bg|contact_bg|process_bg|home_img02|home_rice_brown)/.test(f)) return { cls: 'Archive · context', proves: 'Rice, fields and grains: mood, not proof', action: 'Not used; licensed context photographs serve this role' };
  if (/^home_img01_/.test(f)) return { cls: 'Archive · slogan banner (text in raster)', proves: 'The 2014 slogan (carried over as text)', action: 'Not used as an image' };
  if (/^pankao_logo/.test(f)) return { cls: 'A · logo (2014 wording)', proves: 'The oval PK mark', action: 'Redrawn as vector (D21); request the original artwork' };
  if (/^certified_logo/.test(f)) return { cls: 'Research lead only', proves: 'Marks shown in 2014; not current certification', action: 'Never shown; request current certificates (D05–D07)' };
  return { cls: 'Interface chrome', proves: 'Not content (flags, bars, arrows, backgrounds)', action: 'Not used' };
};

const used = new Map<string, string[]>();
for (const a of assets) {
  const m = a.sourceUrl.match(/images\/([^/?#]+)$/);
  if (a.rightsBasis === 'first-party-legacy-unconfirmed' && m) used.set(m[1]!, [...(used.get(m[1]!) ?? []), a.id]);
}
const files = readdirSync(DIR).filter((f) => /\.(jpe?g|gif|png)$/i.test(f)).sort();
const esc = (s: string) => s.replace(/\|/g, '\\|');
const rows = files.map((f) => { const k = kind(f); const u = used.get(f); return `| ${f} | ${size(f)} | ${k.cls} | ${k.proves} | ${u ? u.join(', ') : '—'} | ${u ? 'In use. ' + k.action : k.action} |`; });
const stock = assets.filter((a) => a.rightsBasis === 'licensed-stock');
const counts = files.reduce<Record<string, number>>((o, f) => { const c = kind(f).cls; o[c] = (o[c] ?? 0) + 1; return o; }, {});

const md = `# Media inventory

Generated by \`scripts/media-inventory.ts\` from the research copy of the 2014 site and the asset ledger. Source classes, as the premium audit defines them:
- **A** is actual Pankao: packs, products, plant, process. It is primary proof, enhanced conservatively and approved by the owner.
- **B** is licensed illustrative imagery: context only, labelled and credited.
- **C** is generated decorative imagery, of which there is none.
Every in-use file's edits are in \`ASSET_LEDGER.md\` (crop and edit log).

## The 2014 website: ${files.length} files

${Object.entries(counts).map(([c, n]) => `- ${c}: ${n}`).join('\n')}

| File | Pixels | Class | What it can prove | Used as | Action |
|---|---|---|---|---|---|
${rows.join('\n')}

## Licensed illustrative photographs (class B): ${stock.length}

| Asset | Subject | Author | Licence | Source |
|---|---|---|---|---|
${stock.map((a) => `| ${a.id} | ${esc(a.subject)} | ${esc(a.sourceOwner)} | ${esc(a.permissionReference ?? '')} | ${a.sourceUrl} |`).join('\n')}

## To request from the company (the audit's minimum premium asset pack)

1. Original files of every class-A image in use above, with who took them and when.
2. Two hero pack shots of current packs.
3. Four dry-noodle macro shots, one per format.
4. Four controlled serving ideas, made with Pankao's own noodles.
5. Five process stages: rice selection, forming, oven drying, inspection, packing.
6. Three OEM and packaging images: bags, cartons, pallet preparation.
7. Two quality or inspection images (with consent if a person is shown).
8. Two factory and location images: exterior with entrance, loading point.
9. Two people or heritage images, with consent.
`;
writeFileSync(join(ROOT, 'docs/generated/MEDIA_INVENTORY.md'), md);
console.log(`media-inventory: ${files.length} legacy files, ${stock.length} licensed → docs/generated/MEDIA_INVENTORY.md`);
